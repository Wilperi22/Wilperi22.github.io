#!/usr/bin/env bash
# Add (or replace) a demo video and publish it to the live site.
#
#   ./add-video.sh <project-id|showreel> <video-file>   add or replace a video
#   ./add-video.sh --remove <project-id|showreel>       remove a video
#   ./add-video.sh                                      show which projects have videos
#
# The video is converted to a web-friendly MP4 (H.264, max 1080p), saved as
# assets/videos/<id>.mp4, registered in assets/videos/videos.js, then committed
# and pushed so the live site updates within a minute or two.
set -euo pipefail
cd "$(dirname "$0")"
DIR=assets/videos
MAX_MB=95   # GitHub rejects files over 100 MB

ids() { node -e 'global.window={};require("./js/data.js");console.log(["showreel",...window.PORTFOLIO.projects.map(p=>p.id)].join("\n"))'; }
valid() { ids | grep -qxF -- "$1"; }

manifest() {
  local out="$DIR/videos.js" first=1 f id dur
  {
    echo '/* Generated by add-video.sh — do not edit by hand. */'
    printf 'window.PORTFOLIO_VIDEOS = {'
    for f in "$DIR"/*.mp4; do
      [ -e "$f" ] || continue
      id=$(basename "$f" .mp4)
      dur=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$f" | awk '{printf "%d", $1 + 0.5}')
      [ $first = 1 ] || printf ','
      first=0
      printf '\n  "%s": { "src": "%s?v=%s", "duration": %s }' "$id" "$f" "$(stat -c %Y "$f")" "${dur:-0}"
    done
    printf '\n};\n'
  } > "$out"
}

status() {
  echo "Videos:"
  for id in $(ids); do
    if [ -f "$DIR/$id.mp4" ]; then printf '  ✓ %-24s %s\n' "$id" "$(du -h "$DIR/$id.mp4" | cut -f1)"
    else printf '  · %-24s (placeholder)\n' "$id"; fi
  done
}

publish() {
  git rev-parse --git-dir >/dev/null 2>&1 || { echo "Not a git repository — saved locally only."; return; }
  git add -A "$DIR"
  if git diff --cached --quiet; then echo "Nothing to publish."; return; fi
  git commit -q -m "$1"
  if git remote get-url origin >/dev/null 2>&1; then
    git push -q origin HEAD && echo "Published — the live site updates in a minute or two."
  else echo "Committed (no remote configured, so not pushed)."; fi
}

if [ $# -eq 0 ]; then status; echo; echo "Usage: ./add-video.sh <id> <video-file>   |   ./add-video.sh --remove <id>"; exit 0; fi

if [ "$1" = "--remove" ]; then
  id=${2:?usage: ./add-video.sh --remove <id>}
  valid "$id" || { echo "Unknown id: $id"; status; exit 1; }
  rm -f "$DIR/$id.mp4"; manifest; status; publish "Remove $id demo video"; exit 0
fi

id=$1; src=${2:?usage: ./add-video.sh <id> <video-file>}
valid "$id" || { echo "Unknown id: $id"; echo; status; exit 1; }
[ -f "$src" ] || { echo "File not found: $src"; exit 1; }

tmp=$(mktemp --suffix=.mp4); trap 'rm -f "$tmp"' EXIT
echo "Converting $(basename "$src") for the web…"
ffmpeg -nostdin -loglevel error -stats -y -i "$src" \
  -vf "scale='trunc(min(1920,iw)/2)*2':-2" -c:v libx264 -preset medium -crf 26 -pix_fmt yuv420p \
  -c:a aac -b:a 128k -movflags +faststart "$tmp"

mb=$(( $(stat -c %s "$tmp") / 1048576 ))
if [ "$mb" -ge "$MAX_MB" ]; then
  echo "The converted video is ${mb} MB — over GitHub's limit (${MAX_MB} MB). Trim it or record a shorter demo."; exit 1
fi
mv "$tmp" "$DIR/$id.mp4"; chmod 644 "$DIR/$id.mp4"
manifest; status; publish "Add $id demo video"
